import { describe, expect, it } from 'vitest';
import { parseBudgetFromRequest } from '../../supabase/functions/_shared/budget.ts';

describe('parseBudgetFromRequest', () => {
  it.each([
    ['다음 주 회사 워크숍, 너무 캐주얼하지 않은 가을 오피스룩. 예산은 20만원 정도', 200000],
    ['예산 20만으로 데이트룩', 200000],
    ['20만 원 이하로 맞춰줘', 200000],
    ['10~20만원 사이 하객룩', 200000],
    ['10만~20만 원', 200000],
    ['50만원대 하객룩', 599999],
    ['3만원대 티셔츠', 39999],
    ['200,000원 이하', 200000],
    ['300000원 안에서', 300000],
    ['2.5만원 이내', 25000],
    ['100만원 정도까지 괜찮아', 1000000],
    ['under 200k won please', 200000],
    ['budget $150', 202500],
    ['under ₩300,000', 300000],
    ['10만원~20만원', 200000],
    ['10만 원 ~ 20만 원', 200000],
    ['10만원에서 20만원 사이', 200000],
    ['5만원-10만원', 100000],
    ['5만원 이상 10만원 이하', 100000],
    ['50만원대로 맞춰줘', 599999],
    ['예산 20만 대학생 룩', 200000],
    ['30만원 대신 20만원으로', 200000],
  ])('reads %s as %d', (text, expected) => {
    expect(parseBudgetFromRequest(text)).toBe(expected);
  });

  it.each([
    '캐주얼 오피스룩 - 격식과 편안함을 동시에 잡는 스마트 캐주얼',
    '주말에 아내랑 가벼운 등산 겸 산책. 등산복 티 너무 안 나게',
    '키 170에 80kg 남자, 20대 후반',
    '50만원 이상이어도 괜찮아요',
    '10만원짜리 니트에 어울리는 바지',
    '',
  ])('finds no budget in %s', (text) => {
    expect(parseBudgetFromRequest(text)).toBeNull();
  });
});
